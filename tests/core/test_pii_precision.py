def test_precision_fixes_are_idempotent():
    for text in (
        "我的电话是 1 3 8 1 2 3 4 5 6 7 8",
        "寄到样例大厦18楼1805",
        "寄到样例路100号 明天能到城里吗",
        "19.9 29.9 39.9 49.9 哪个规格划算",
    ):
        once = mask_pii(text)
        assert mask_pii(once) == once


