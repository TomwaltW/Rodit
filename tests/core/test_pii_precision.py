def test_merchant_evidence_keeps_size_and_price_lists():
    """商家自己的尺码、价格事实进提示词【依据】前也过 mask_pii，不能被当成手机号、地址遮掉。"""
    detail = Evidence(
        id="item:i_900:detail:1",
        source=EvidenceSource.ITEM,
        label="商品详情",
        content="脚内长 13.5 14.5 15.5 16.5 17.5 cm，对应 22 24 26 28 30 码",
    )
    faq = Evidence(
        id="faq:12",
        source=EvidenceSource.FAQ,
        label="FAQ",
        content="套装里2组替换刷头，另购 19.9 29.9 39.9 49.9 四档",
    )
    assert "13.5 14.5 15.5 16.5 17.5 cm" in evidence_line(detail)
    line = evidence_line(faq)
    assert "套装里2组替换刷头" in line and "19.9 29.9 39.9 49.9 四档" in line
    assert "[" not in line.split("]", 1)[1]


